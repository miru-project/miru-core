// nodeModulesExercise is the assertion block an extension uses to prove every
// bundled node module loads and works from inside the real runtime. Each entry
// is a snippet whose LAST expression is the value returned as the single search
// result title, so the host decodes it and the test can assert on it.
var nodeModulesExercise = []struct {
	name string
	expr string
	want string
}{
	{
		name: "linkedom",
		expr: `(() => {
			const { parseHTML } = require("linkedom");
			const { document } = parseHTML("<html><body><p id='x'>hello</p></body></html>");
			return document.querySelector("#x").textContent;
		})()`,
		want: "hello",
	},
	{
		name: "md5",
		expr: `(() => {
			const md5 = require("md5");
			return md5("abc");
		})()`,
		want: "900150983cd24fb0d6963f7d28e17f72",
	},
	{
		name: "crypto-js",
		expr: `(() => {
			const CryptoJS = require("crypto-js");
			return CryptoJS.MD5("abc").toString();
		})()`,
		want: "900150983cd24fb0d6963f7d28e17f72",
	},
	{
		name: "jsencrypt",
		expr: `(() => {
			const JSEncrypt = require("jsencrypt");
			const enc = new JSEncrypt();
			enc.setPublicKey("-----BEGIN PUBLIC KEY-----\nMFwwDQYJKoZIhvcNAQEBBQADSwAwSAJBALVZQ+1cNGvJx8O8Z0nqL0sKQqOe0yMk\nXVBqJPLZmN0hbBcdBHhkZfmuHDxzXeHIzMkP6NlDsFAJ5ZwIDAQAB\n-----END PUBLIC KEY-----");
			return typeof enc.encrypt === "function" ? "ok" : "missing";
		})()`,
		want: "ok",
	},
	{
		name: "zlib",
		expr: `(() => {
			const zlib = require("zlib");
			const enc = zlib.bytesFromBase64(
				typeof btoa === "function" ? btoa("miru") : Buffer.from("miru").toString("base64")
			);
			const out = zlib.gzipSync(enc);
			return out.length > 0 ? "ok" : "empty";
		})()`,
		want: "ok",
	},
	{
		name: "url",
		expr: `(() => {
			const u = new URL("https://example.com/a/b?x=1");
			return u.hostname + u.pathname;
		})()`,
		want: "example.com/a/b",
	},
	{
		name: "crypto-getRandomValues",
		expr: `(() => {
			const a = new Uint8Array(16);
			crypto.getRandomValues(a);
			return a.length === 16 ? "ok" : "bad";
		})()`,
		want: "ok",
	},
	{
		name: "console",
		expr: `(() => {
			// console must be a usable object with the standard methods.
			return typeof console.log === "function" && typeof console.error === "function"
				? "ok" : "bad";
		})()`,
		want: "ok",
	},
	{
		name: "host-primitives",
		expr: `(() => {
			// The host primitives the runtime scripts call directly.
			return typeof jsRequest === "function"
				&& typeof btoa === "function"
				&& typeof atob === "function"
				&& typeof fetch === "function"
				? "ok" : "bad";
		})()`,
		want: "ok",
	},
	{
		name: "miru-object",
		expr: `(() => {
			return typeof Miru.pkg === "string" && typeof Miru.name === "string"
				&& typeof Miru.website === "string"
				? "ok" : "bad";
		})()`,
		want: "ok",
	},
}

// nodeModulesV1Source builds a V1 extension whose latest() runs expr.
func nodeModulesV1Source(pkg, expr, want string) string {
	return "// ==MiruExtension==\n" +
		"// @name         Node Modules\n" +
		"// @package      " + pkg + "\n" +
		"// ==/MiruExtension==\n\n" +
		"export default class extends Extension {\n" +
		"    async load() {}\n" +
		"    async latest(page) {\n" +
		"        let v;\n" +
		"        try {\n" +
		"            v = " + expr + ";\n" +
		"        } catch (e) {\n" +
		"            v = \"THREW: \" + (e && e.message ? e.message : String(e));\n" +
		"        }\n" +
		"        return [{ title: String(v), url: \"https://example.com\" }];\n" +
		"    }\n" +
		"}\n"
}

// nodeModulesV2Source builds a V2 extension whose latest() runs expr.
func nodeModulesV2Source(pkg, expr string) string {
	return "// ==MiruExtension==\n" +
		"// @name         Node Modules\n" +
		"// @package      " + pkg + "\n" +
		"// @apiVersion   2\n" +
		"// ==/MiruExtension==\n\n" +
		"async function load() {}\n" +
		"async function latest(page) {\n" +
		"    let v;\n" +
		"    try {\n" +
		"        v = " + expr + ";\n" +
		"    } catch (e) {\n" +
		"        v = \"THREW: \" + (e && e.message ? e.message : String(e));\n" +
		"    }\n" +
		"    return [{ title: String(v), url: \"https://example.com\" }];\n" +
		"}\n"
}

// runNodeModuleCases drives every nodeModulesExercise entry through the REAL
// runtime for one API version, one extension per case so a module that breaks
// one version cannot influence another. It is the regression guard for the
// "all node module tests must pass without exception" requirement: a module that
// is requireable only in a bare goja VM but not inside a real extension call
// (missing registry wiring, missing base runtime declaration, a host primitive
// that is not registered) fails here.
func runNodeModuleCases(t *testing.T, apiVersion string) {
	t.Helper()

	for i, tc := range nodeModulesExercise {
		t.Run(fmt.Sprintf("v%s/%s", apiVersion, tc.name), func(t *testing.T) {
			pkg := fmt.Sprintf("nodemods.%s.v%s.%d", tc.name, apiVersion, i)
			dir := t.TempDir()

			var src string
			if apiVersion == "2" {
				src = nodeModulesV2Source(pkg, tc.expr)
			} else {
				src = nodeModulesV1Source(pkg, tc.expr, tc.want)
			}
			require.NoError(t, os.WriteFile(filepath.Join(dir, pkg+".js"), []byte(src), 0644))

			ApiPkgCache.Remove(pkg)
			deleteInstanceState(pkg)

			InitRuntime(dir, AssetsFS)
			api := waitForPkg(t, pkg)
			require.Equal(t, apiVersion, api.Ext.ApiVersion)
			require.Empty(t, api.Ext.Error, "extension must compile and load cleanly")

			items, err := Latest[proto.ExtensionListItem](pkg, 1)
			require.NoError(t, err, "%s must be usable from an extension call", tc.name)
			require.Len(t, items, 1)
			assert.Equal(t, tc.want, items[0].Title,
				"%s must work for API v%s", tc.name, apiVersion)
		})
	}
}

// TestNodeModulesWorkInExtensionV1 is the V1 half: no @apiVersion tag, so the
// runtime routes it to the class-based V1 runtime.
func TestNodeModulesWorkInExtensionV1(t *testing.T) {
	runNodeModuleCases(t, "1")
}

// TestNodeModulesWorkInExtensionV2 is the V2 half: top-level functions, so the
// runtime routes it to the V2 runtime with its own base script.
func TestNodeModulesWorkInExtensionV2(t *testing.T) {
	runNodeModuleCases(t, "2")
}